// Turn the Page — build step (SPEC.md 14.1).
// Run from turn-the-page/: `node build.mjs`. Node built-ins only.
// Reads src/shell.html and replaces each slot comment with a source file,
// then writes the standalone index.html (works from file://).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const read = (p) => readFileSync(join(root, p), 'utf8');

// Slot comment -> source file. JS sources are ES modules for Node; in the
// page they share one script scope, so `export` keywords are stripped.
const slots = [
  { marker: '/*CSS*/', file: 'src/style.css', js: false },
  { marker: '//ENGINE', file: 'src/engine.js', js: true },
  { marker: '//ART', file: 'src/art.js', js: true },
  { marker: '//CONTENT', file: 'src/content/maya.js', js: true },
  { marker: '//UI', file: 'src/ui.js', js: true }
];

function fail(msg) {
  console.error('build failed: ' + msg);
  process.exit(1);
}

let html = read('src/shell.html');

for (const s of slots) {
  let src = read(s.file);
  if (/<\/(script|style)/i.test(src)) fail(s.file + ' contains a closing </script> or </style> tag');
  if (s.js) {
    if (/^\s*import\s/m.test(src)) fail(s.file + ' uses import; inlined sources share one scope instead');
    src = src.replace(/^export\s+/gm, '');
  }
  const escaped = s.marker.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
  const re = new RegExp('^[ \\t]*' + escaped + '[ \\t]*$', 'gm');
  const count = (html.match(re) || []).length;
  if (count !== 1) fail('slot ' + s.marker + ' found ' + count + ' times in src/shell.html (expected 1)');
  html = html.replace(re, () => '/* ---- ' + s.file + ' ---- */\n' + src.trimEnd());
}

if (!/^<!doctype html>/i.test(html)) fail('shell must start with <!doctype html>');
if (!/<head>\s*<meta charset="utf-8">/i.test(html)) fail('<meta charset="utf-8"> must come first in <head>');
if (!/<meta name="viewport"/i.test(html)) fail('missing viewport meta');

html = html.replace(/^<!doctype html>\n?/i, '<!doctype html>\n<!-- Generated by build.mjs. Do not edit: change the files in src/ and run `node build.mjs`. -->\n');

writeFileSync(join(root, 'index.html'), html);
console.log('wrote index.html (' + Buffer.byteLength(html) + ' bytes)');
