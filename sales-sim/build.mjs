// Builds the single-file page from src/.
//   node sales-sim/build.mjs                 -> sales-sim/index.html (complete document)
//   node sales-sim/build.mjs --artifact out  -> also writes the body-only fragment for claude.ai Artifacts
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const read = (p) => readFileSync(here(p), 'utf8');
const fragment = read('./src/shell.html')
  .replace('/*CSS*/', () => read('./src/style.css').trim())
  .replace('//ENGINE', () => read('./src/engine.js').trim())
  .replace('//UI', () => read('./src/ui.js').trim());

const doc = '<!doctype html>\n<html lang="en-GB">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">\n</head>\n<body>\n'
  + '<!-- Generated by build.mjs from src/. Edit the files in src/ and rebuild. -->\n' + fragment + '\n</body>\n</html>\n';
writeFileSync(here('./index.html'), doc);
console.log('wrote sales-sim/index.html', (doc.length / 1024).toFixed(0) + ' KB');

const i = process.argv.indexOf('--artifact');
if (i > 0 && process.argv[i + 1]) {
  writeFileSync(process.argv[i + 1], fragment + '\n');
  console.log('wrote', process.argv[i + 1]);
}
